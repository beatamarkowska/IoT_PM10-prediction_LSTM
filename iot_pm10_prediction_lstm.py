def fill_gaps_sensor(sensor_df):
    time_diff = sensor_df.index.to_series().diff()

    short_gaps_mask = time_diff < pd.Timedelta(hours=12)
    sensor_df.loc[short_gaps_mask, :] = sensor_df.loc[short_gaps_mask, :].interpolate(method='time', limit_direction='both')


    long_gaps_mask = (time_diff >= pd.Timedelta(hours=12)) & (time_diff <= pd.Timedelta(hours=24))

    for idx in sensor_df.index[long_gaps_mask]:
        start_time = idx - pd.Timedelta(hours=23)

        try:

            data_to_copy = sensor_df.loc[start_time:idx - pd.Timedelta(hours=1)]

            if not data_to_copy.empty:

                missing_range = pd.date_range(start=idx - (time_diff[idx] - pd.Timedelta(hours=1)), end=idx - pd.Timedelta(hours=1), freq='H')
                data_to_copy = data_to_copy.iloc[-len(missing_range):]
                data_to_copy.index = missing_range


                sensor_df.update(data_to_copy)
        except KeyError:

            continue


    sensor_df['UTC time'] = sensor_df.index
    return sensor_df

final_df = geo_df_filtered.groupby('id').apply(fill_gaps_sensor)
