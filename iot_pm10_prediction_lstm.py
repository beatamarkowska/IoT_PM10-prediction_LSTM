"""The fill_gaps_sensor(sensor_df) function fills time gaps in data from one sensor using two methods depending on the length of the time gap:
 1. Interpolation of gaps shorter than 12 hours,
 2. Insertion of data from the previous day for gaps between 12h and 24h.
"""

geo_df_filtered['UTC time'] = pd.to_datetime(geo_df_filtered['UTC time'])
