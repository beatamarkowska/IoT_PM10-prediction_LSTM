"""The find_nan_streaks function finds and describes continuous breaks (strings of missing values ​​/ NaN) in a specified column for a single sensor. It operates on the passed DataFrame and returns information about each streak of missing values."""

def find_nan_streaks(sensor_df, column):
    sensor_df = sensor_df.copy()
    sensor_df['is_nan'] = sensor_df[column].isna()
    sensor_df['nan_group'] = (sensor_df['is_nan'] != sensor_df['is_nan'].shift()).cumsum()

    nan_periods = sensor_df[sensor_df['is_nan']].groupby('nan_group').agg(
        start=('UTC time', 'first'),
        end=('UTC time', 'last'),
        count=('UTC time', 'count')
    ).reset_index(drop=True)

    nan_periods['duration'] = nan_periods['end'] - nan_periods['start']

    return nan_periods

